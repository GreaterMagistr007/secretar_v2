import { describe, expect, it } from 'vitest';
import { occurrencesInRange, occursOn } from './recurrence';

describe('occursOn, повторение none', () => {
  it('вхождение только в день старта', () => {
    expect(occursOn('2026-09-15', 'none', '2026-09-15')).toBe(true);
  });

  it('день до старта — нет вхождения', () => {
    expect(occursOn('2026-09-15', 'none', '2026-09-14')).toBe(false);
  });

  it('день после старта — нет вхождения', () => {
    expect(occursOn('2026-09-15', 'none', '2026-09-16')).toBe(false);
  });
});

describe('occursOn, повторение daily', () => {
  it('вхождение в день старта', () => {
    expect(occursOn('2026-09-15', 'daily', '2026-09-15')).toBe(true);
  });

  it('вхождение в следующий день', () => {
    expect(occursOn('2026-09-15', 'daily', '2026-09-16')).toBe(true);
  });

  it('вхождение через год', () => {
    expect(occursOn('2026-09-15', 'daily', '2027-09-15')).toBe(true);
  });

  it('до старта вхождений нет', () => {
    expect(occursOn('2026-09-15', 'daily', '2026-09-14')).toBe(false);
  });
});

describe('occursOn, повторение weekly', () => {
  it('вхождение в день старта', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-15')).toBe(true);
  });

  it('через семь дней — вхождение', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-22')).toBe(true);
  });

  it('через четырнадцать дней — вхождение', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-29')).toBe(true);
  });

  it('через шесть дней вхождения нет', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-21')).toBe(false);
  });

  it('через восемь дней вхождения нет', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-23')).toBe(false);
  });

  it('считает через конец месяца', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-10-06')).toBe(true);
    expect(occursOn('2026-09-15', 'weekly', '2026-10-05')).toBe(false);
  });

  it('считает через конец года', () => {
    expect(occursOn('2026-12-28', 'weekly', '2027-01-04')).toBe(true);
    expect(occursOn('2026-12-28', 'weekly', '2027-01-03')).toBe(false);
  });

  it('за семь дней до старта вхождения нет, хотя кратность соблюдена', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-08')).toBe(false);
  });

  it('за четырнадцать дней до старта вхождения нет', () => {
    expect(occursOn('2026-09-15', 'weekly', '2026-09-01')).toBe(false);
  });
});

describe('occursOn, повторение monthly', () => {
  it('то же число в следующем месяце — вхождение', () => {
    expect(occursOn('2026-09-15', 'monthly', '2026-10-15')).toBe(true);
  });

  it('старт 15-го не даёт вхождения 14-го', () => {
    expect(occursOn('2026-09-15', 'monthly', '2026-10-14')).toBe(false);
  });

  it('старт 31 января переносится на 28 февраля невисокосного года', () => {
    expect(occursOn('2026-01-31', 'monthly', '2026-02-28')).toBe(true);
    expect(occursOn('2026-01-31', 'monthly', '2026-02-27')).toBe(false);
  });

  it('старт 31 января даёт 29 февраля високосного года', () => {
    expect(occursOn('2026-01-31', 'monthly', '2028-02-29')).toBe(true);
    expect(occursOn('2026-01-31', 'monthly', '2028-02-28')).toBe(false);
  });

  it('старт 31 января даёт 31 марта — в месяце из 31 дня перенос не нужен', () => {
    expect(occursOn('2026-01-31', 'monthly', '2026-03-31')).toBe(true);
    expect(occursOn('2026-01-31', 'monthly', '2026-03-28')).toBe(false);
  });

  it('старт 30 января переносится на 28 февраля невисокосного года', () => {
    expect(occursOn('2026-01-30', 'monthly', '2026-02-28')).toBe(true);
  });

  it('старт 28 февраля даёт 28 марта, а не последний день марта', () => {
    expect(occursOn('2026-02-28', 'monthly', '2026-03-28')).toBe(true);
    expect(occursOn('2026-02-28', 'monthly', '2026-03-31')).toBe(false);
  });

  it('то же число месяцем ранее старта — нет вхождения', () => {
    expect(occursOn('2026-09-15', 'monthly', '2026-08-15')).toBe(false);
  });
});

describe('occursOn, повторение yearly', () => {
  it('то же число и месяц через год — вхождение', () => {
    expect(occursOn('2026-09-15', 'yearly', '2027-09-15')).toBe(true);
  });

  it('другой месяц того же числа вхождения не даёт', () => {
    expect(occursOn('2026-09-15', 'yearly', '2027-10-15')).toBe(false);
  });

  it('старт 29 февраля 2024 переносится на 28 февраля 2025', () => {
    expect(occursOn('2024-02-29', 'yearly', '2025-02-28')).toBe(true);
  });

  it('старт 29 февраля 2024 переносится на 28 февраля 2026', () => {
    expect(occursOn('2024-02-29', 'yearly', '2026-02-28')).toBe(true);
  });

  it('старт 29 февраля 2024 даёт 29 февраля 2028 и не даёт 28 февраля 2028', () => {
    expect(occursOn('2024-02-29', 'yearly', '2028-02-29')).toBe(true);
    expect(occursOn('2024-02-29', 'yearly', '2028-02-28')).toBe(false);
  });

  it('старт 1 марта не даёт вхождения 28 февраля', () => {
    expect(occursOn('2026-03-01', 'yearly', '2027-02-28')).toBe(false);
    expect(occursOn('2026-03-01', 'yearly', '2027-03-01')).toBe(true);
  });

  it('то же число и месяц годом ранее старта — нет вхождения', () => {
    expect(occursOn('2026-03-01', 'yearly', '2025-03-01')).toBe(false);
  });
});

describe('переходы через границы месяца и года', () => {
  it('за 31 января идёт 1 февраля', () => {
    expect(occurrencesInRange('2026-01-31', 'daily', '2026-01-31', '2026-02-01')).toEqual([
      '2026-01-31',
      '2026-02-01',
    ]);
  });

  it('за 31 декабря идёт 1 января следующего года', () => {
    expect(occurrencesInRange('2026-12-31', 'daily', '2026-12-31', '2027-01-01')).toEqual([
      '2026-12-31',
      '2027-01-01',
    ]);
  });

  it('в невисокосном году февраль заканчивается 28-м', () => {
    expect(occurrencesInRange('2026-02-27', 'daily', '2026-02-27', '2026-03-01')).toEqual([
      '2026-02-27',
      '2026-02-28',
      '2026-03-01',
    ]);
  });

  it('в високосном году февраль заканчивается 29-м', () => {
    expect(occurrencesInRange('2024-02-28', 'daily', '2024-02-28', '2024-03-01')).toEqual([
      '2024-02-28',
      '2024-02-29',
      '2024-03-01',
    ]);
  });
});

describe('occurrencesInRange', () => {
  it('диапазон целиком до старта даёт пустой результат', () => {
    expect(occurrencesInRange('2026-09-15', 'daily', '2026-09-01', '2026-09-14')).toEqual([]);
  });

  it('перевёрнутый диапазон даёт пустой результат', () => {
    expect(occurrencesInRange('2026-09-15', 'daily', '2026-09-30', '2026-09-01')).toEqual([]);
  });

  it('ежедневная задача даёт 42 даты на сетке месяца', () => {
    const dates = occurrencesInRange('2026-08-31', 'daily', '2026-08-31', '2026-10-11');

    expect(dates).toHaveLength(42);
    expect(dates[0]).toBe('2026-08-31');
    expect(dates[41]).toBe('2026-10-11');
  });

  it('еженедельная задача даёт ровно шесть дат на сетке месяца', () => {
    expect(occurrencesInRange('2026-08-31', 'weekly', '2026-08-31', '2026-10-11')).toEqual([
      '2026-08-31',
      '2026-09-07',
      '2026-09-14',
      '2026-09-21',
      '2026-09-28',
      '2026-10-05',
    ]);
  });

  it('ежемесячная задача даёт одну дату внутри одного месяца', () => {
    expect(occurrencesInRange('2026-09-15', 'monthly', '2026-09-01', '2026-09-30')).toEqual([
      '2026-09-15',
    ]);
  });

  it('задача без повторений даёт только день старта', () => {
    expect(occurrencesInRange('2026-09-15', 'none', '2026-09-01', '2026-09-30')).toEqual([
      '2026-09-15',
    ]);
  });

  it('обе границы диапазона включительно', () => {
    expect(occurrencesInRange('2026-09-15', 'weekly', '2026-09-15', '2026-09-22')).toEqual([
      '2026-09-15',
      '2026-09-22',
    ]);
  });

  it('результат отсортирован по возрастанию', () => {
    const dates = occurrencesInRange('2026-01-31', 'monthly', '2026-01-01', '2026-06-30');

    expect(dates).toEqual([...dates].sort());
    expect(dates).toEqual([
      '2026-01-31',
      '2026-02-28',
      '2026-03-31',
      '2026-04-30',
      '2026-05-31',
      '2026-06-30',
    ]);
  });
});
